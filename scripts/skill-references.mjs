// The skills' references, written from the documentation pages as Markdown that agents read offline: the
// jlib-official skill's list of components and a page per component (what the site's component page says: its
// properties, events, slots, methods, styling, typing and examples), and the syware-ux skill's list of patterns and
// a page per pattern, whole. `npm run generate` writes them; `--check` fails when one is stale.
import { readFileSync } from 'node:fs';

import { dedent } from '../src/lib/text.ts';

const SITE_URL = 'https://bioleyl.github.io/jlib';
const GENERATED =
  '<!-- Generated by scripts/generate-index.mjs (npm run generate) from the documentation pages: do not edit. -->';
const LEVELS = [
  { heading: 'Atoms', level: 'atom' },
  { heading: 'Molecules', level: 'molecule' },
  { heading: 'Organisms', level: 'organism' },
  { heading: 'Templates', level: 'template' },
];
const TAG_PREFIX = /^jl-/;
const ROUTE_LINK = /\]\((\/[^)\s]*)\)/g;
const COMPONENT_ROUTE = /^\/components\/([a-z-]+)$/;
const PATTERN_ROUTE = /^\/patterns\/([a-z-]+)$/;
const STYLE_ATTRIBUTE = / style="[^"]*"/g;
const LINE_BREAK = /\s*\n\s*/g;
const TABLE_PIPE = /\|/g;
const CUSTOM_PROPERTY = /^--/;
const ESCAPE = /\\(.)/g;
// A string as Biome writes it: in single quotes, or in double quotes when it holds an apostrophe.
const STRING = String.raw`(['"])((?:(?!\1)[^\\]|\\.)*)\1`;
const PRINCIPLES = /UX_PRINCIPLES: readonly UxPrinciple\[\] = \[([\s\S]*?)\n\];/;
const PRINCIPLE = new RegExp(String.raw`text:\s*${STRING},\s*title:\s*(['"])((?:(?!\3)[^\\]|\\.)*)\3`, 'g');
const EXAMPLES_NOTE =
  "HTML as the site renders it, with its layout classes (`row`, `stack`, `narrow`, `muted`), which are not jlib's: a view writes the same components by class in JSX. A script's `root` is the example's element.";
const CODE_FENCES = { bash: 'bash', css: 'css', html: 'html', text: 'text', ts: 'ts' };

const FENCE = '```';
const fence = (language, code) => [`${FENCE}${language}`, code, FENCE];
const oneLine = (text) => text.trim().replace(LINE_BREAK, ' ');
const levelIndex = (level) => LEVELS.findIndex((entry) => entry.level === level);
const slugOf = (tag) => tag.replace(TAG_PREFIX, '');
const componentPage = (tag) => `${SITE_URL}/components/${slugOf(tag)}`;

/**
 * The site's links in a text (`[Forms](/patterns/forms)`), made links of the skill: to its own reference when it has
 * one, else to the page on the site.
 */
function withLinks(text, localTarget) {
  return text.replace(ROUTE_LINK, (_link, route) => `](${localTarget(route) ?? `${SITE_URL}${route}`})`);
}

// --- Components ---

/** Components by level, then by name, as the site lists them. */
export const sortedComponents = (docs) =>
  [...docs].sort((a, b) => levelIndex(a.level) - levelIndex(b.level) || a.name.localeCompare(b.name, 'en'));

/** From a component's reference, to another's. */
const componentTarget = (route) => {
  const slug = COMPONENT_ROUTE.exec(route)?.[1];
  return slug === undefined ? undefined : `jl-${slug}.md`;
};

function propLine(prop) {
  const bound = prop.attribute === undefined ? 'property only' : `attribute \`${prop.attribute}\``;
  return `- \`${prop.name}\` (${bound}): \`${oneLine(prop.type)}\`, default \`${prop.default}\`. ${oneLine(prop.description)}`;
}

const jsxEventName = (name) => `on${name.charAt(0).toUpperCase()}${name.slice(1)}`;

const eventLine = (event) =>
  `- \`${event.name}\` (\`${jsxEventName(event.name)}\` in JSX), detail \`${oneLine(event.detail)}\`: ${oneLine(event.description)}`;

const slotLine = (slot) =>
  `- ${slot.name === '' ? 'The default slot' : `\`${slot.name}\``}: ${oneLine(slot.description)}`;

const methodLine = (method) => `- \`${oneLine(method.signature)}\`: ${oneLine(method.description)}`;

const styleLine = (style) =>
  CUSTOM_PROPERTY.test(style.name)
    ? `- \`${style.name}\` (custom property): ${oneLine(style.description)}`
    : `- \`${style.name}\` (part, \`::part(${style.name})\`): ${oneLine(style.description)}`;

/** A section of a reference: its heading, a line on how to use what it lists, then its lines; nothing when empty. */
const listSection = (heading, intro, lines) =>
  lines.length === 0 ? [] : [`## ${heading}`, '', ...(intro ? [intro, ''] : []), ...lines, ''];

/**
 * The playground's element, as a view writes it (by class, its children too, typed by their own props) and as HTML
 * writes it.
 */
function useSection(doc, snippets, propsOf) {
  const source = {
    attributes: doc.playground.attributes,
    childProps: propsOf,
    className: doc.className,
    content: doc.playground.content ?? '',
    props: doc.props,
    tag: doc.tag,
  };
  return [
    '## Use',
    '',
    ...fence('ts', snippets.importSnippet(doc.className, ...snippets.childClasses(source.content))),
    '',
    ...fence('tsx', snippets.jsxSnippet(source)),
    '',
    ...fence('html', snippets.htmlSnippet(source)),
    '',
  ];
}

function typingSection(typing, snippets) {
  if (typing === undefined) {
    return [];
  }
  return [
    '## Typing',
    '',
    withLinks(typing.description.trim(), componentTarget),
    '',
    ...fence('ts', snippets.shownSnippet(typing.code)),
    '',
    ...fence('tsx', snippets.shownSnippet(typing.jsx)),
    '',
  ];
}

function exampleLines(example) {
  return [
    `### ${example.title}`,
    '',
    ...(example.description ? [withLinks(example.description.trim(), componentTarget), ''] : []),
    ...fence('html', dedent(example.html)),
    '',
    ...(example.script ? [...fence('js', dedent(example.script)), ''] : []),
  ];
}

/**
 * A component's reference: what its page on the site says, as Markdown. `propsOf` gives the props of any component by
 * its tag, for the children its examples write.
 */
export function componentReference(doc, snippets, propsOf) {
  return [
    GENERATED,
    '',
    `# ${doc.name}: \`${doc.tag}\``,
    '',
    doc.summary,
    '',
    `- Class \`${doc.className}\`, ${doc.level === 'atom' ? 'an' : 'a'} ${doc.level}: \`import { ${doc.className} } from '@syware/jlib';\``,
    `- On the site: ${componentPage(doc.tag)}`,
    '',
    ...(doc.description ? [withLinks(doc.description.trim(), componentTarget), ''] : []),
    ...useSection(doc, snippets, propsOf),
    ...listSection(
      'Properties',
      'Inputs: a JSX prop sets one, code calls `.set(value)` and `.get()`, HTML writes the attribute (lists and objects as JSON).',
      doc.props.map(propLine)
    ),
    ...listSection(
      'Events',
      'In JSX, the `on…` prop, its handler given the detail; in code, `events.register(name, (detail) => …)`. They do not bubble.',
      (doc.events ?? []).map(eventLine)
    ),
    ...listSection('Slots', '', (doc.slots ?? []).map(slotLine)),
    ...listSection('Methods', '', (doc.methods ?? []).map(methodLine)),
    ...listSection('Styling', '', (doc.styling ?? []).map(styleLine)),
    ...typingSection(doc.typing, snippets),
    ...(doc.examples.length === 0
      ? []
      : ['## Examples', '', EXAMPLES_NOTE, '', ...doc.examples.flatMap(exampleLines)]),
  ].join('\n');
}

const componentLine = (doc) =>
  `- **${doc.name}** ([\`${doc.className}\`, \`${doc.tag}\`](components/${doc.tag}.md)): ${doc.summary}`;

/** The jlib-official skill's list of components, each linked to its reference. */
export function componentCatalogue(docs) {
  return [
    GENERATED,
    '',
    "# jlib's components",
    '',
    `${docs.length} components, by level. Each links to its reference: properties, events, slots, methods, styling and`,
    'examples. In an app, the declarations of the installed version are the last word:',
    '`node_modules/@syware/jlib/dist/<level>/<tag>.d.ts`. One missing from `dist` is newer than the installed jlib.',
    '',
    ...LEVELS.flatMap(({ heading, level }) => [
      `## ${heading}`,
      '',
      ...docs.filter((doc) => doc.level === level).map(componentLine),
      '',
    ]),
  ].join('\n');
}

// --- Patterns ---

/** From a pattern's reference, to another's. */
const patternTarget = (route) => {
  const slug = PATTERN_ROUTE.exec(route)?.[1];
  return slug === undefined ? undefined : `${slug}.md`;
};

const tableCell = (text) => withLinks(oneLine(text), patternTarget).replace(TABLE_PIPE, '\\|');

const tableRow = (cells) => `| ${cells.map(tableCell).join(' | ')} |`;

// A preview is the site's illustration: the components and their attributes, without the styles that frame it.
const previewHtml = (html) => dedent(html).replace(STYLE_ATTRIBUTE, '');

function guideline(label, rule) {
  return [
    `**${label}**${rule.text ? `: ${withLinks(rule.text, patternTarget)}` : ''}`,
    '',
    ...fence('html', previewHtml(rule.preview)),
    '',
  ];
}

/** A block of a pattern's section, as Markdown lines. */
function blockLines(block) {
  switch (block.kind) {
    case 'text':
      return [withLinks(block.text, patternTarget), ''];
    case 'list':
      return [...block.items.map((item) => `- ${withLinks(item, patternTarget)}`), ''];
    case 'rules':
      return [...guideline('Do', block.do), ...guideline("Don't", block.dont)];
    case 'preview':
      return [
        ...fence('html', previewHtml(block.html)),
        '',
        ...(block.caption ? [withLinks(block.caption, patternTarget), ''] : []),
      ];
    case 'table':
      return [tableRow(block.head), `|${block.head.map(() => '---|').join('')}`, ...block.rows.map(tableRow), ''];
    case 'note':
      return [`> ${withLinks(oneLine(block.text), patternTarget)}`, ''];
    case 'code':
      return [...fence(CODE_FENCES[block.language] ?? 'text', dedent(block.code)), ''];
    default:
      throw new Error(`A pattern block of an unknown kind: ${block.kind}.`);
  }
}

const componentLink = (tag) => `[\`${tag}\`](${componentPage(tag)})`;

/** A pattern page in full, as Markdown. */
export function patternReference(pattern) {
  const components =
    pattern.components.length === 0
      ? []
      : [
          '## Components',
          '',
          `${pattern.components.map(componentLink).join(', ')}. Their references are in the jlib-official skill.`,
          '',
        ];
  return [
    GENERATED,
    '',
    `# ${pattern.title}`,
    '',
    withLinks(pattern.lead, patternTarget),
    '',
    `On the site: ${SITE_URL}${pattern.path}`,
    '',
    "The previews are the site's illustrations, in HTML, with its layout classes (`row`, `stack`, `muted`), which are",
    "not jlib's: a view writes the same components by class in JSX.",
    '',
    ...pattern.sections.flatMap((section) => [`## ${section.heading}`, '', ...section.blocks.flatMap(blockLines)]),
    ...components,
  ].join('\n');
}

const unescaped = (text) => text.replace(ESCAPE, '$1');

const principleLine = (match) => `- **${unescaped(match[4])}**: ${unescaped(match[2])}`;

const patternLine = (page) =>
  `- **[${page.title}](patterns/${page.slug}.md)** (\`${page.slug}\`): ${page.summary} ${page.lead}`;

/** The syware-ux skill's list of patterns: the principles, then the pages in reading order, each linked. */
export function patternCatalogue(pages, listFile) {
  const principles = [...(PRINCIPLES.exec(readFileSync(listFile, 'utf8'))?.[1] ?? '').matchAll(PRINCIPLE)];
  return [
    GENERATED,
    '',
    "# SyWare's UX patterns",
    '',
    'The principles every SyWare app follows, then the pattern pages in reading order, each in full in `patterns/`.',
    '',
    '## Principles',
    '',
    ...principles.map(principleLine),
    '',
    '## Pages',
    '',
    ...pages.map(patternLine),
    '',
  ].join('\n');
}
