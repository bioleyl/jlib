// Writes src/index.ts (every export of the library) and src/all.ts (defines every component), from the files in
// src/atoms, src/molecules, src/organisms and src/templates. `--check` fails instead of writing when they are stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = join(import.meta.dirname, '..', 'src');
const LEVELS = ['atoms', 'molecules', 'organisms', 'templates'];
const MODULE_PATTERN = /\.tsx?$/;
const COMPONENT_PATTERN = /export class (\w+) extends \w+ \{\s+static readonly selector = '([\w-]+)'/g;
const HEADER = '// Generated by scripts/generate-index.mjs (npm run generate): do not edit by hand.\n';
const CHECK = process.argv.includes('--check');

const modulesOf = (directory) =>
  readdirSync(join(SRC, directory))
    .filter((file) => MODULE_PATTERN.test(file))
    .sort()
    .map((file) => `${directory}/${file.replace(MODULE_PATTERN, '')}`);

const componentsOf = (modulePath) => {
  const file = ['.tsx', '.ts'].map((extension) => join(SRC, `${modulePath}${extension}`));
  const source = file.map((path) => tryRead(path)).find((text) => text !== null) ?? '';
  return [...source.matchAll(COMPONENT_PATTERN)].map((match) => ({ className: match[1], selector: match[2] }));
};

function tryRead(path) {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return null;
  }
}

const componentModules = LEVELS.flatMap(modulesOf);
const typeModules = modulesOf('types');

const index = [
  HEADER,
  "export { JlElement } from './base/jl-element';",
  "export { JlFormControl } from './base/jl-form-control';",
  "export { clampedNumber, jsonOf, oneOf } from './lib/attributes';",
  "export { define } from './lib/define';",
  "export { computePosition, followAnchor, PLACEMENTS, placeFloating } from './lib/floating';",
  "export { COMMON_ICONS } from './lib/icon-set';",
  "export { hasIcon, iconElement, iconNames, registerIcons } from './lib/icons';",
  "export { CONTROL_SIZES, TONE_ICONS, TONES } from './lib/options';",
  "export { adoptTokens } from './lib/tokens';",
  "export { TOKEN_STYLES } from './styles/shared';",
  ...typeModules.map((path) => `export type * from './${path}';`),
  ...componentModules.map((path) => `export * from './${path}';`),
  '',
].join('\n');

const components = componentModules.flatMap(componentsOf).sort((a, b) => a.className.localeCompare(b.className));

const all = [
  HEADER,
  '// Defines every component and registers the common icons, for pages that write tags in HTML without a bundler',
  '// choosing what they use.',
  `import { COMMON_ICONS, define, registerIcons, ${components.map((component) => component.className).join(', ')} } from './index';`,
  '',
  'registerIcons(COMMON_ICONS);',
  `define(${components.map((component) => component.className).join(', ')});`,
  '',
  "export * from './index';",
  '',
].join('\n');

const outputs = [
  { content: index, path: join(SRC, 'index.ts') },
  { content: all, path: join(SRC, 'all.ts') },
];

const stale = outputs.filter((output) => tryRead(output.path) !== output.content);

if (CHECK && stale.length > 0) {
  console.error(`Stale: ${stale.map((output) => output.path).join(', ')}. Run npm run generate.`);
  process.exit(1);
}

for (const output of stale) {
  writeFileSync(output.path, output.content);
}

console.log(`${components.length} components: ${components.map((component) => component.selector).join(', ')}`);
