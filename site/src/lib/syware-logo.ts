const pathOf = (part: LogoPart): SVGPathElement => {
  const path = document.createElementNS(SVG_NAMESPACE, 'path');
  path.setAttribute('d', part.d);
  path.setAttribute('transform', `translate(${part.x} ${part.y})`);
  // In style, not attributes: only CSS reads custom properties, so the ink follows the theme.
  path.style.fill = part.ink ? INK : BLUE;
  return path;
};

type Box = typeof MARK_BOX;

/** Some parts of the logo in a box, `height` pixels tall, named for screen readers. */
function drawing(box: Box, parts: readonly LogoPart[], height: number): SVGSVGElement {
  const svg = document.createElementNS(SVG_NAMESPACE, 'svg');
  svg.setAttribute('viewBox', `${box.x} ${box.y} ${box.width} ${box.height}`);
  svg.setAttribute('height', String(height));
  svg.setAttribute('width', String(Math.round((height * box.width) / box.height)));
  svg.setAttribute('role', 'img');
  svg.setAttribute('aria-label', 'SyWare');
  svg.setAttribute('shape-rendering', 'geometricPrecision');
  const group = document.createElementNS(SVG_NAMESPACE, 'g');
  group.setAttribute('transform', ROOT_TRANSFORM);
  group.append(...parts.map(pathOf));
  svg.append(group);
  return svg;
}

/** The SyWare mark alone, `height` pixels tall. */
export const sywareMark = (height: number): SVGSVGElement =>
  drawing(
    MARK_BOX,
    PARTS.filter((part) => part.mark),
    height
  );
